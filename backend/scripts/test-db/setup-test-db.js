const DDL_NON_COLUMN_TOKENS = new Set(['CREATE', 'PRIMARY', 'FOREIGN', 'CONSTRAINT', 'UNIQUE', 'CHECK', ')']);

function expectedColumnsFromDdl(ddl) {
  return String(ddl || '')
    .split('\n')
    .map((line) => line.trim().replace(/,$/, ''))
    .map((line) => String(line.split(/\s+/)[0] || '').replace(/"/g, '').toUpperCase())
    .filter((token) => /^[A-Z][A-Z0-9_$#]*$/.test(token) && !DDL_NON_COLUMN_TOKENS.has(token));
}

async function tableExists(name) {
  const result = await execute(
    `SELECT COUNT(*) AS TOTAL FROM ALL_TABLES WHERE OWNER = :owner AND TABLE_NAME = :tableName`,
    { owner: schema, tableName: safeOracleIdentifier(name) },
    { operation: `testDb.tableExists.${name}` }
  );
  const row = Array.isArray(result?.rows) ? result.rows[0] : null;
  return Number(row?.TOTAL || 0) > 0;
}

async function createMissingTables() {
  const created = [];
  const existing = [];
  for (const table of tables) {
    if (await tableExists(table.name)) {
      existing.push(table.name);
      continue;
    }
    await execute(table.ddl, {}, { operation: `testDb.create.${table.name}` });
    created.push(table.name);
  }
  return { created, existing };
}

async function listColumns(name) {
  const result = await execute(
    `
      SELECT COLUMN_NAME
        FROM ALL_TAB_COLUMNS
       WHERE OWNER = :owner
         AND TABLE_NAME = :tableName
    `,
    { owner: schema, tableName: safeOracleIdentifier(name) },
    { operation: `testDb.listColumns.${name}` }
  );
  return new Set((Array.isArray(result?.rows) ? result.rows : []).map((row) => String(row.COLUMN_NAME || '').toUpperCase()));
}

async function validateTableColumns() {
  const mismatches = [];
  for (const table of tables) {
    const expected = expectedColumnsFromDdl(table.ddl);
    const actual = await listColumns(table.name);
    const missing = expected.filter((column) => !actual.has(column));
    if (missing.length) {
      mismatches.push({ table: table.name, missing });
    }
  }

  if (mismatches.length) {
    const err = new Error(
      `El esquema ${schema} tiene tablas existentes con columnas faltantes: ${mismatches
        .map((item) => `${item.table}(${item.missing.join(', ')})`)
        .join('; ')}`
    );
    err.code = 'TEST_DB_SCHEMA_MISMATCH';
    err.mismatches = mismatches;
    throw err;
  }
}

