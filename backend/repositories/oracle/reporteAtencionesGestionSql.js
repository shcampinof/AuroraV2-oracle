const { normalizedMojibakeSqlExpr } = require('./sqlFragments');
const { buildAutomaticBlock3ClosureSql } = require('./auroraCaseClosuresSql');

// Reglas del SQL suministrado para los indicadores 1.1–1.6.
// aplicar_tablero_sindicados = 0: condenados usan los criterios del tablero;
// sindicados conservan sus hitos y reglas de cierre anteriores.
function filledSql(expression) {
  return `CASE WHEN NVL(TRIM(REGEXP_REPLACE(REPLACE(${expression}, UNISTR('\\00A0'), ' '), '[[:space:]]+', ' ')), '-') IN ('-', '--') THEN 0 ELSE 1 END`;
}

function negativeSql(expression) {
  const value = `NVL(${normalizedMojibakeSqlExpr(expression)}, '-')`;
  return `CASE WHEN ${value} = 'NO' OR ${value} LIKE 'NO APLICA%' OR ${value} LIKE 'NO CUMPLE%' THEN 1 ELSE 0 END`;
}

function buildReportGestionCtes() {
  return `
GESTION_NORMALIZADA AS (
  SELECT G.*,
    NVL(${normalizedMojibakeSqlExpr("G.ACTUACION_ADELANTAR")}, '-') AS ACTUACION_N,
    NVL(${normalizedMojibakeSqlExpr("G.SENTIDO_DECISION")}, '-') AS DECISION_N,
    NVL(${normalizedMojibakeSqlExpr("G.SE_PRESENTA_RECURSO")}, '-') AS RECURSO_N,
    NVL(${normalizedMojibakeSqlExpr("G.DECISION_USUARIO")}, '-') AS USUARIO_N,
    NVL(${normalizedMojibakeSqlExpr("G.OTRAS_SOLICITUDES_TRAMITAR")}, '-') AS OTRAS_N,
    CASE WHEN ${normalizedMojibakeSqlExpr("G.CIERRE_CASO")} IN (
      'SE CIERRA PORQUE LA PERSONA FUE TRASLADADA A UN ERON DE COMPETENCIA DE OTRA REGIONAL DE LA DEFENSORIA DEL PUEBLO',
      'SE CIERRA PORQUE LA PERSONA SE ENCUENTRA EN LIBERTAD',
      'SE CIERRA PORQUE LA PERSONA YA NO ESTA EN EL ERON POR RAZON AJENA A ESTE TRAMITE.',
      'CIERRE AUTOMATICO POR CAMBIO DE ERON O REGIONAL.',
      'CIERRE AUTOMATICO POR CAMBIO DE REGIONAL.',
      'CIERRE AUTOMATICO POR ACTUALIZACION RELEVANTE DE SISIPEC.',
      'OTRO MOTIVO.'
    ) THEN 1 ELSE 0 END AS CIERRE_EXPLICITO
  FROM DNDP.GESTION_JURIDICA G
  JOIN DNDP.SITUACION_CARCELARIA ALCANCE_S ON ALCANCE_S.ID_SITUACION = G.ID_SITUACION
  JOIN PERSONAS_DEL_DEFENSOR ALCANCE ON ALCANCE.ID_PERSONA = ALCANCE_S.ID_PERSONA
),
GESTION_UTILIDAD AS (
  SELECT G.*,
    CASE WHEN ACTUACION_N LIKE '%UTILIDAD PUBLICA%'
      OR (
        ${filledSql("G.ACTUACION_ADELANTAR")} = 0
        AND DECISION_N IN (
          'NIEGA UTILIDAD PUBLICA',
          'OTORGA UTILIDAD PUBLICA'
        )
      )
      THEN 1 ELSE 0
    END AS ES_UTILIDAD
  FROM GESTION_NORMALIZADA G
),
GESTION_DECISION AS (
  SELECT G.*,
    CASE WHEN (
      ES_UTILIDAD = 0
      AND DECISION_N IN (
        'NO CONCEDE LA SOLICITUD',
        'NO CONCEDE SUBROGADO PENAL'
      )
    ) OR (
      ES_UTILIDAD = 1
      AND DECISION_N = 'NIEGA UTILIDAD PUBLICA'
    ) THEN 1 ELSE 0 END AS DECISION_NEGATIVA
  FROM GESTION_UTILIDAD G
),
GESTIONES AS (
  SELECT G.*,
    CASE WHEN ${normalizedMojibakeSqlExpr("COALESCE(TRIM(TO_CHAR(S.SITUACION_JURIDICA_ACTUALIZADA)), TO_CHAR(S.SITUACION))")} LIKE '%SINDICAD%' THEN
      CASE
        WHEN CIERRE_EXPLICITO = 1
          OR ACTUACION_N LIKE 'NO SE AVANZARA%'
          OR ${filledSql("G.SENTIDO_DECISION_RESUELVE_RECURSO")} = 1
          OR DECISION_N LIKE '%REVOCA MEDIDA%'
          OR DECISION_N LIKE '%SUSTITUYE MEDIDA%'
          THEN 1

        WHEN G.FECHA_DECISION_RECURSO IS NOT NULL
          AND ${filledSql("G.SENTIDO_DECISION_RESUELVE_RECURSO")} = 0
          THEN 0

        WHEN DECISION_N LIKE '%NIEGA LA SOLICITUD%'
          THEN CASE WHEN RECURSO_N = 'NO' THEN 1 ELSE 0 END

        ELSE 0
      END
    ELSE
      CASE WHEN (${buildAutomaticBlock3ClosureSql('G')}) IS NOT NULL THEN 1
      WHEN (
        ${negativeSql("G.LIBERTAD_CONDICIONAL")} = 1
        AND ${negativeSql("G.PRISION_DOMICILIARIA_MITAD_PENA")} = 1
        AND ${negativeSql("G.PROCEDENCIA_PENA_CUMPLIDA")} = 1
        AND ${negativeSql("G.PROCEDENCIA_ACUMULACION_PENAS")} = 1
        AND (
          ${filledSql("G.UTILIDAD_PUBLICA")} = 0
          OR ${negativeSql("G.UTILIDAD_PUBLICA")} = 1
        )
        AND OTRAS_N = 'NINGUNA'
        AND G.FECHA_ANALISIS IS NOT NULL
        AND NOT (
          DECISION_NEGATIVA = 1
          AND RECURSO_N IN ('SI', 'S?')
          AND ${filledSql("G.SENTIDO_DECISION_RESUELVE_RECURSO")} = 0
        )
      )
      OR CIERRE_EXPLICITO = 1
      OR ${filledSql("G.SENTIDO_DECISION_RESUELVE_RECURSO")} = 1
      OR (
        ${filledSql("G.DECISION_USUARIO")} = 1
        AND USUARIO_N NOT LIKE 'SI%'
      )
      OR ACTUACION_N LIKE '%NINGUNA%'
      OR ACTUACION_N LIKE '%NO PROCEDE NADA%'
      OR (
        ES_UTILIDAD = 1
        AND (
          ${normalizedMojibakeSqlExpr("G.CUMPLE_REQUISITO_MARGINALIDAD")} = 'NO'
          OR ${normalizedMojibakeSqlExpr("G.CUMPLE_REQUISITO_JEFATURA_HOGAR")} = 'NO'
        )
      )
      OR (
        DECISION_NEGATIVA = 1
        AND (
          RECURSO_N = 'NO'
          OR ${filledSql("G.SENTIDO_DECISION_RESUELVE_RECURSO")} = 1
        )
      )
      OR (
        ES_UTILIDAD = 0
        AND ${filledSql("G.SENTIDO_DECISION")} = 1
        AND DECISION_N NOT IN (
          'NO CONCEDE LA SOLICITUD',
          'NO CONCEDE SUBROGADO PENAL'
        )
      )
      OR (
        ES_UTILIDAD = 1
        AND ${filledSql("G.SENTIDO_DECISION")} = 1
        AND DECISION_N <> 'NIEGA UTILIDAD PUBLICA'
      )
      THEN 1 ELSE 0 END
    END AS CERRADA
  FROM GESTION_DECISION G
  JOIN DNDP.SITUACION_CARCELARIA S
    ON S.ID_SITUACION = G.ID_SITUACION
),
GESTION_TABLERO_1 AS (
  SELECT G.*,
    CASE WHEN ${normalizedMojibakeSqlExpr("COALESCE(TRIM(TO_CHAR(S.SITUACION_JURIDICA_ACTUALIZADA)), TO_CHAR(S.SITUACION))")} LIKE '%SINDICAD%'
         THEN 0 ELSE 1 END AS T_APLICA,
    CASE WHEN G.FECHA_ANALISIS IS NOT NULL
      AND ${filledSql("G.LIBERTAD_CONDICIONAL")} = 1
      AND ${filledSql("G.PRISION_DOMICILIARIA_MITAD_PENA")} = 1
      AND ${filledSql("G.PROCEDENCIA_PENA_CUMPLIDA")} = 1
      AND ${filledSql("G.PROCEDENCIA_ACUMULACION_PENAS")} = 1
      AND ${filledSql("G.OTRAS_SOLICITUDES_TRAMITAR")} = 1
      AND ${filledSql("SUBSTR(G.RESUMEN_ANALISIS_CASO, 1, 400)")} = 1
    THEN 1 ELSE 0 END AS T_ANALISIS_COMPLETO,
    CASE WHEN NVL(${normalizedMojibakeSqlExpr("G.LIBERTAD_CONDICIONAL")}, '-') LIKE 'SI PROCEDE SOLICITUD DE LIBERTAD CONDICIONAL%'
      OR NVL(${normalizedMojibakeSqlExpr("G.LIBERTAD_CONDICIONAL")}, '-') LIKE 'SI PROCEDERA PROXIMAMENTE LIBERTAD CONDICIONAL%'
      OR NVL(${normalizedMojibakeSqlExpr("G.PRISION_DOMICILIARIA_MITAD_PENA")}, '-') LIKE 'SI PROCEDE SOLICITUD DE PRISION DOMICILIARIA%'
      OR NVL(${normalizedMojibakeSqlExpr("G.PRISION_DOMICILIARIA_MITAD_PENA")}, '-') LIKE 'SI PROCEDERA PROXIMAMENTE PRISION DOMICILIARIA%'
      OR NVL(${normalizedMojibakeSqlExpr("G.UTILIDAD_PUBLICA")}, '-') = 'SI CUMPLE REQUISITOS OBJETIVOS'
      OR NVL(${normalizedMojibakeSqlExpr("G.PROCEDENCIA_PENA_CUMPLIDA")}, '-') = 'SI'
      OR NVL(${normalizedMojibakeSqlExpr("G.PROCEDENCIA_ACUMULACION_PENAS")}, '-') = 'SI'
      OR G.OTRAS_N <> 'NINGUNA'
    THEN 1 ELSE 0 END AS T_TIENE_PROCEDENCIA,
    CASE WHEN G.USUARIO_N IN (
      'NO, PORQUE DESEA TRAMITAR LA SOLICITUD A TRAVES DE SU DEFENSOR DE CONFIANZA',
      'NO DESEA TRAMITAR LA SOLICITUD',
      'NO AVANZARA PORQUE NO PUEDE DEMOSTRAR ARRAIGO FUERA DE PRISION',
      'EL USUARIO ES RENUENTE A LA ATENCION'
    ) THEN 1 ELSE 0 END AS T_CERRADO_DECISION,
    CASE WHEN G.FECHA_ENTREVISTA IS NOT NULL
      AND ${filledSql("G.DECISION_USUARIO")} = 1
      AND ${filledSql("G.ACTUACION_ADELANTAR")} = 1
      AND ${filledSql("G.REQUIERE_PRUEBAS")} = 1
      AND ${filledSql("G.PODER_AVANZAR_SOLICITUD")} = 1
    THEN 1 ELSE 0 END AS T_ENTREVISTA_COMPLETA
  FROM GESTIONES G
  JOIN DNDP.SITUACION_CARCELARIA S
    ON S.ID_SITUACION = G.ID_SITUACION
),
GESTION_TABLERO_2 AS (
  SELECT T.*,
    CASE WHEN T.T_ANALISIS_COMPLETO = 1 AND T.T_TIENE_PROCEDENCIA = 1
         THEN 1 ELSE 0 END AS T_ELEGIBLE,
    CASE WHEN T.T_ANALISIS_COMPLETO = 1 AND T.T_TIENE_PROCEDENCIA = 1
          AND T.T_CERRADO_DECISION = 0 AND T.T_ENTREVISTA_COMPLETA = 1
          AND (T.FECHA_PRESENTACION_SOLICITUD_AUTORIDAD IS NOT NULL
               OR T.FECHA_RADICACION_UTILIDAD IS NOT NULL)
         THEN 1 ELSE 0 END AS T_RADICADA
  FROM GESTION_TABLERO_1 T
),
GESTION_TABLERO_3 AS (
  SELECT T.*,
    CASE WHEN T.T_RADICADA = 1 AND T.FECHA_DECISION_AUTORIDAD IS NOT NULL
          AND T.DECISION_N IN ('CONCEDE LA SOLICITUD', 'CONCEDE SUBROGADO PENAL', 'OTORGA UTILIDAD PUBLICA')
         THEN 1 ELSE 0 END AS T_FAVORABLE,
    CASE WHEN T.T_RADICADA = 1 AND T.FECHA_DECISION_AUTORIDAD IS NOT NULL
          AND T.DECISION_N IN ('NIEGA UTILIDAD PUBLICA', 'NO CONCEDE LA SOLICITUD', 'NO CONCEDE SUBROGADO PENAL')
         THEN 1 ELSE 0 END AS T_DESFAVORABLE
  FROM GESTION_TABLERO_2 T
),
GESTION_TABLERO_4 AS (
  SELECT T.*,
    CASE WHEN T.T_DESFAVORABLE = 1
          AND T.FECHA_PRESENTACION_RECURSO IS NOT NULL
          AND T.RECURSO_N IN ('SI', 'S?')
         THEN 1 ELSE 0 END AS T_RECURSO
  FROM GESTION_TABLERO_3 T
),
GESTIONES_T AS (
  SELECT T.*,
    CASE
      WHEN T.T_APLICA = 0 THEN T.CERRADA
      WHEN T.CIERRE_EXPLICITO = 1
        OR (T.T_ANALISIS_COMPLETO = 1 AND T.T_TIENE_PROCEDENCIA = 0)
        OR (T.T_ELEGIBLE = 1 AND T.T_CERRADO_DECISION = 1)
        OR T.T_FAVORABLE = 1
        OR (T.T_DESFAVORABLE = 1 AND T.T_RECURSO = 0)
        OR (T.T_RECURSO = 1 AND ${filledSql("T.SENTIDO_DECISION_RESUELVE_RECURSO")} = 1)
      THEN 1 ELSE 0
    END AS T_CERRADA,
    CASE
      WHEN T.T_APLICA = 1
        AND T.T_RECURSO = 1
        AND ${filledSql("T.SENTIDO_DECISION_RESUELVE_RECURSO")} = 1
        THEN CAST(COALESCE(T.FECHA_DECISION_RECURSO, T.FECHA_DECISION_AUTORIDAD) AS DATE)
      WHEN T.T_APLICA = 1 AND (T.T_FAVORABLE = 1 OR T.T_DESFAVORABLE = 1)
        THEN CAST(T.FECHA_DECISION_AUTORIDAD AS DATE)
      WHEN T.T_APLICA = 1 AND T.T_ELEGIBLE = 1 AND T.T_CERRADO_DECISION = 1
        THEN CAST(COALESCE(T.FECHA_ENTREVISTA, T.FECHA_ANALISIS) AS DATE)
      WHEN T.T_APLICA = 1 AND T.T_ANALISIS_COMPLETO = 1 AND T.T_TIENE_PROCEDENCIA = 0
        THEN CAST(T.FECHA_ANALISIS AS DATE)
      ELSE CAST(COALESCE(
        T.FECHA_DECISION_RECURSO,
        T.FECHA_DECISION_AUTORIDAD,
        T.FECHA_PRESENTACION_RECURSO,
        T.FECHA_RECURSO_DESFAVORABLE,
        T.FECHA_ENTREVISTA,
        T.FECHA_ANALISIS,
        T.FECHA_REGISTRO
      ) AS DATE)
    END AS T_FECHA_CIERRE
  FROM GESTION_TABLERO_4 T
)
  `;
}

module.exports = { buildReportGestionCtes };
